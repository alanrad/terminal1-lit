const defaultLibrary: IconLibrary = {
  name: 'default',
  resolver: name => `https://cdn.jsdelivr.net/npm/bootstrap-icons@1.11.3/icons/${name}.svg`,
};

const systemLibrary: IconLibrary = {
  name: 'system',
  resolver: name => {
    if (name in systemIcons) {
      return `data:image/svg+xml,${encodeURIComponent(systemIcons[name])}`;
    }
    return '';
  },
};

let registry: IconLibrary[] = [defaultLibrary, systemLibrary];
let watchedIcons: T1Icon[] = [];

export function watchIcon(icon: T1Icon) {
  watchedIcons.push(icon);
}

export function unwatchIcon(icon: T1Icon) {
  watchedIcons = watchedIcons.filter(el => el !== icon);
}

export function getIconLibrary(name?: string) {
  return registry.find(lib => lib.name === name);
}

export function registerIconLibrary(name: string, options: Omit<IconLibrary, 'name'>) {
  unregisterIconLibrary(name);
  registry.push({
    name,
    resolver: options.resolver,
    mutator: options.mutator,
    spriteSheet: options.spriteSheet,
  });

  watchedIcons.forEach(icon => {
    if (icon.library === name) {
      icon.setIcon();
    }
  });
}

export function unregisterIconLibrary(name: string) {
  registry = registry.filter(lib => lib.name !== name);
}
